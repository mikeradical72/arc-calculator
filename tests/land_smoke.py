"""Browser smoke test for the land finder (desktop + Android-like mobile). Usage: python3 tests/land_smoke.py <url>"""
import asyncio, sys, json
from playwright.async_api import async_playwright
URL = (sys.argv[1] if len(sys.argv) > 1 else 'http://localhost:8000/').split('#')[0]
OUT = '/workspace/arcic'
fails = []
def check(c, msg):
    print(('OK   ' if c else 'FAIL ') + msg)
    if not c: fails.append(msg)
async def num(pg, sel): return int((await pg.inner_text(sel)).replace(',', ''))
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        errs = []
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900})
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: m.type == 'error' and errs.append(m.text))
        answers = []
        def on_dialog(d):
            asyncio.ensure_future(d.accept(answers.pop(0)) if (answers and d.type == 'prompt') else d.accept())
        pg.on('dialog', on_dialog)
        await pg.goto(URL); await pg.wait_for_selector('body[data-land-ready="1"]', timeout=60000)
        total = await num(pg, '#lcShown'); check(total > 12000, f'desktop loads both counties ({total} parcels)')
        # filters
        await pg.select_option('#fCounty', 'richland'); await pg.wait_for_timeout(500)
        rich = await num(pg, '#lcShown'); check(0 < rich < total, f'county filter -> {rich}')
        await pg.eval_on_selector('#fNc', "e => { e.value = 60; e.dispatchEvent(new Event('input', {bubbles:true})); }"); await pg.wait_for_timeout(500)
        hi = await num(pg, '#lcShown'); check(0 < hi < rich, f'NCCPI>=60 filter -> {hi}')
        await pg.click('#fReset'); await pg.wait_for_timeout(500)
        check(await num(pg, '#lcShown') == total, 'clear filters restores all')
        await pg.fill('#fAcMin', '150'); await pg.fill('#fAcMax', '170'); await pg.wait_for_timeout(500)
        q = await num(pg, '#lcShown'); check(0 < q < total, f'acre range 150-170 -> {q}')
        await pg.click('#fReset'); await pg.wait_for_timeout(400)
        # parcel size presets
        async def row_acres(page):
            return [float(t.replace(',', '').replace(' ac', '')) for t in await page.locator('#plist .pi .acbig').all_inner_texts()]
        await pg.uncheck('#lInView'); await pg.wait_for_timeout(300)
        sizes = {}
        for k, lo, hi in [('40', 35, 45), ('80', 75, 85), ('160', 150, 170), ('320', 300, None)]:
            await pg.click(f'#fSize button[data-k="{k}"]'); await pg.wait_for_timeout(400)
            n = await num(pg, '#lcShown'); ac = await row_acres(pg); sizes[k] = n
            on = await pg.get_attribute(f'#fSize button[data-k="{k}"]', 'aria-pressed')
            check(0 < n < total and ac and all(lo <= a and (hi is None or a <= hi) for a in ac) and on == 'true'
                  and await pg.input_value('#fAcMin') == str(lo) and await pg.input_value('#fAcMax') == ('' if hi is None else str(hi)),
                  f'size preset ~{k}: {n} parcels, list rows {min(ac) if ac else None}-{max(ac) if ac else None} ac')
        check(sizes['160'] == q, 'preset ~160 matches typed 150-170 range')
        await pg.fill('#fAcMin', '60'); await pg.fill('#fAcMax', '100'); await pg.wait_for_timeout(400)
        ac = await row_acres(pg)
        check(all(60 <= a <= 100 for a in ac) and 'custom' in await pg.inner_text('#vSize') and await pg.locator('#fSize button.on').count() == 0, 'custom min/max 60-100 (no preset lit)')
        # details show acres prominently
        await pg.click('#plist .pi [data-act="info"]'); await pg.wait_for_timeout(200)
        check('acres' in await pg.inner_text('#inspAcres'), 'details panel shows acres up top')
        await pg.click('#inspect [data-x]')
        await pg.check('#lInView'); await pg.click('#fReset'); await pg.wait_for_timeout(400)
        # rule out from list (no confirm)
        first = await pg.get_attribute('#plist .pi', 'data-id')
        await pg.click('#plist .pi .main'); await pg.wait_for_timeout(200)
        check(await num(pg, '#lcHidden') == 1 and await num(pg, '#lcShown') == total - 1, 'list tap rules out immediately')
        check(await pg.query_selector(f'#plist .pi[data-id="{first}"]') is None, 'ruled-out row gone from list')
        check(await pg.is_visible('#toast'), 'undo toast shown')
        # rule out on map: zoom to next parcel, click map center
        nxt = await pg.get_attribute('#plist .pi', 'data-id')
        await pg.click(f'#plist .pi[data-id="{nxt}"] [data-act="zoom"]'); await pg.wait_for_timeout(1200)
        box = await pg.locator('#map').bounding_box()
        await pg.mouse.click(box['x'] + box['width'] / 2, box['y'] + box['height'] / 2); await pg.wait_for_timeout(300)
        hidden_ids = await pg.evaluate('window.__land.hidden.toJSON()')
        check(len(hidden_ids) == 2 and hidden_ids[-1] == nxt, f'map click rules out the parcel under the cursor ({hidden_ids[-1] if hidden_ids else None})')
        await pg.screenshot(path=f'{OUT}/land-zoomed.png')
        # undo
        await pg.click('#lbUndo'); await pg.wait_for_timeout(300)
        check(await num(pg, '#lcHidden') == 1, 'undo restores the last one')
        # persistence
        await pg.reload(); await pg.wait_for_selector('body[data-land-ready="1"]', timeout=60000)
        check(await num(pg, '#lcHidden') == 1, 'ruled-out parcels persist after reload')
        # show hidden + restore by tap
        await pg.check('#lbShowHidden'); await pg.wait_for_timeout(400)
        await pg.uncheck('#lInView'); await pg.wait_for_timeout(300)
        await pg.select_option('#lSort', 'acres'); await pg.wait_for_timeout(300)
        ruled = await pg.query_selector_all('#plist .pi.ruled')
        check(len(ruled) >= 0, 'show ruled out toggle works')
        await pg.uncheck('#lbShowHidden'); await pg.check('#lInView'); await pg.select_option('#lSort', 'nccpi'); await pg.wait_for_timeout(300)
        # inspect -> ARC prefill
        await pg.select_option('#fCounty', 'richland'); await pg.wait_for_timeout(500)
        await pg.click('#plist .pi [data-act="info"]'); await pg.wait_for_timeout(200)
        check(await pg.is_visible('#inspect'), 'details panel opens')
        await pg.click('#inspect [data-act="arc"]'); await pg.wait_for_timeout(400)
        check(pg.url.endswith('#arc') and await pg.input_value('#county') == 'richland', 'ARC/PLC tab prefilled with parcel county')
        await pg.goto(URL + '#land'); await pg.wait_for_selector('body[data-land-ready="1"]', timeout=60000)
        await pg.click('#fReset'); await pg.wait_for_timeout(300)
        await pg.click('#lbRestore'); await pg.wait_for_timeout(300)
        check(await num(pg, '#lcHidden') == 0, 'restore all')
        # ---- separate searches (tabs) ----
        hid = lambda page: page.evaluate('window.__land.hidden.toJSON()')
        check(await pg.locator('#stabList .stab').count() == 1, 'starts with one search tab')
        await pg.uncheck('#lInView'); await pg.click('#fSize button[data-k="160"]'); await pg.wait_for_timeout(400)
        ids1 = [await pg.get_attribute('#plist .pi', 'data-id')]
        await pg.click('#plist .pi .main'); await pg.wait_for_timeout(150)
        ids1.append(await pg.get_attribute('#plist .pi', 'data-id')); await pg.click('#plist .pi .main'); await pg.wait_for_timeout(300)
        check(await hid(pg) == ids1, f'tab 1: ruled out 2 ({ids1})')
        answers.append('Yaggie hunt'); await pg.click('#sNew'); await pg.wait_for_timeout(600)
        check(await pg.locator('#stabList .stab').count() == 2 and 'Yaggie hunt' in await pg.inner_text('#stabList .stab.on'), 'new search tab created and active')
        check(await num(pg, '#lcHidden') == 0 and await pg.input_value('#fAcMin') == '' and await num(pg, '#lcShown') == total, 'new tab: own empty ruled-out list + fresh filters')
        await pg.fill('#fName', 'yAGGie'); await pg.wait_for_timeout(500)
        yn = await num(pg, '#lcShown'); rows = await pg.locator('#plist .pi .o').all_inner_texts()
        check(yn == 259 and rows and all('yaggie' in r.lower() for r in rows) and await pg.locator('#plist .pi mark').count() > 0, f'name search Yaggie -> {yn} parcels, rows highlighted')
        check(any('taxpayer' in r.lower() for r in rows), 'list rows label taxpayer')
        await pg.click('#plist .pi .main'); await pg.wait_for_timeout(300); ids2 = await hid(pg)
        await pg.click('#fStates button[data-v="ND"]'); await pg.wait_for_timeout(400)
        ynd = await num(pg, '#lcShown'); rows = await pg.locator('#plist .pi').count()
        check(0 < ynd < yn, f'Yaggie + mailing state ND -> {ynd}')
        await pg.click('#stabList .stab >> nth=0'); await pg.wait_for_timeout(600)
        check(await hid(pg) == ids1 and await pg.input_value('#fAcMin') == '150' and await pg.input_value('#fName') == '' and await pg.locator('#fStates button.on').count() == 0, 'back on tab 1: its own 2 ruled-out + 150-170, no name/state')
        await pg.click('#stabList .stab >> nth=1'); await pg.wait_for_timeout(600)
        check(await hid(pg) == ids2 and await pg.input_value('#fName') == 'yAGGie' and await num(pg, '#lcShown') == ynd, 'tab 2 keeps its own list + filters')
        await pg.reload(); await pg.wait_for_selector('body[data-land-ready="1"]', timeout=60000); await pg.wait_for_timeout(500)
        check(await pg.locator('#stabList .stab').count() == 2 and 'Yaggie hunt' in await pg.inner_text('#stabList .stab.on') and await hid(pg) == ids2 and await num(pg, '#lcShown') == ynd, 'after reload: active tab, its list and filters restored')
        await pg.click('#stabList .stab >> nth=0'); await pg.wait_for_timeout(600)
        check(await hid(pg) == ids1 and await pg.input_value('#fAcMax') == '170', 'after reload: tab 1 still separate')
        # menu: duplicate, rename, export, import, delete
        await pg.click('#sMenuBtn'); await pg.click('#sMenu [data-m="dup"]'); await pg.wait_for_timeout(500)
        check(await pg.locator('#stabList .stab').count() == 3 and await hid(pg) == ids1 and 'copy' in await pg.inner_text('#stabList .stab.on'), 'duplicate copies list + filters')
        answers.append('Quarters 2'); await pg.click('#sMenuBtn'); await pg.click('#sMenu [data-m="rename"]'); await pg.wait_for_timeout(300)
        check('Quarters 2' in await pg.inner_text('#stabList .stab.on'), 'rename')
        await pg.click('#plist .pi .main'); await pg.wait_for_timeout(300)
        await pg.click('#stabList .stab >> nth=0'); await pg.wait_for_timeout(500)
        check(await hid(pg) == ids1, 'ruling out in the duplicate does not touch the original')
        async with pg.expect_download() as dl:
            await pg.click('#sMenuBtn'); await pg.click('#sMenu [data-m="export"]')
        path = await (await dl.value).path(); ex = json.load(open(path))
        check(ex['format'] == 'baseacre-search' and ex['search']['hidden'] == ids1 and ex['search']['filters']['acMin'] in ('150', 150), 'export JSON has filters + ruled-out list')
        await pg.set_input_files('#sImportFile', path); await pg.wait_for_timeout(700)
        check(await pg.locator('#stabList .stab').count() == 4 and await hid(pg) == ids1 and await pg.input_value('#fAcMin') == '150', 'import JSON opens as a new tab')
        await pg.click('#sMenuBtn'); await pg.click('#sMenu [data-m="delete"]'); await pg.wait_for_timeout(500)
        check(await pg.locator('#stabList .stab').count() == 3, 'delete search tab')
        # outside MN/ND folded into the state filter
        await pg.locator('#stabList .stab', has_text='Yaggie hunt').click(); await pg.wait_for_timeout(500)
        await pg.fill('#fName', ''); await pg.click('#fStates button[data-v="ND"]'); await pg.click('#fStates button[data-v="__out"]'); await pg.wait_for_timeout(500)
        out_n = await num(pg, '#lcShown') + await num(pg, '#lcHidden') * 0
        check(1000 < out_n < 1200, f'Outside MN/ND option -> {out_n}')
        await pg.click('#fStMore'); await pg.wait_for_timeout(200)
        check(await pg.locator('#fStates button').count() == 44, 'all 43 state options + Outside MN/ND')
        await pg.click('#fStates button[data-v="__out"]'); await pg.click('#fStMore'); await pg.fill('#fName', 'Yaggie'); await pg.wait_for_timeout(500)
        await pg.evaluate("window.__land.map.setView([46.27, -96.62], 12); 0"); await pg.wait_for_timeout(2500)
        await pg.screenshot(path=f'{OUT}/land-tabs-desktop.png')
        await pg.click('#plist .pi [data-act="info"]'); await pg.wait_for_timeout(300)
        it = await pg.inner_text('#inspect'); check('Taxpayer' in it and 'Owner' in it and 'Mailing states' in it, 'details show owner, taxpayer and mailing states')
        await pg.click('#inspect [data-x]'); await pg.fill('#fName', ''); await pg.check('#lInView')
        await pg.click('#stabList .stab >> nth=0'); await pg.wait_for_timeout(400)
        await pg.goto(URL); await pg.wait_for_selector('body[data-land-ready="1"]', timeout=60000); await pg.wait_for_timeout(1500)
        await pg.screenshot(path=f'{OUT}/land-desktop-overview.png')
        await pg.evaluate("document.querySelector('#filtersBox').open = false; window.__land.map.setView([46.30, -96.68], 12.5); 0"); await pg.wait_for_timeout(2500)
        await pg.screenshot(path=f'{OUT}/land-desktop.png')
        # mobile (Android-ish, touch)
        m = await b.new_context(viewport={'width': 412, 'height': 915}, device_scale_factor=2, is_mobile=True, has_touch=True,
                                user_agent='Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Mobile Safari/537.36')
        mp = await m.new_page(); mp.on('pageerror', lambda e: errs.append(str(e)))
        await mp.goto(URL); await mp.wait_for_selector('body[data-land-ready="1"]', timeout=60000)
        mt = await num(mp, '#lcShown')
        await mp.locator('#plist .pi .main').first.tap(); await mp.wait_for_timeout(250)
        check(await num(mp, '#lcHidden') == 1 and await num(mp, '#lcShown') == mt - 1, 'mobile: tap list row rules out')
        nid = await mp.get_attribute('#plist .pi', 'data-id')
        await mp.locator(f'#plist .pi[data-id="{nid}"] [data-act="zoom"]').tap(); await mp.wait_for_timeout(1500)
        mb = await mp.locator('#map').bounding_box()
        await mp.touchscreen.tap(mb['x'] + mb['width'] / 2, mb['y'] + mb['height'] / 2); await mp.wait_for_timeout(400)
        ids = await mp.evaluate('window.__land.hidden.toJSON()')
        check(len(ids) == 2 and ids[-1] == nid, 'mobile: tap on map rules out parcel')
        await mp.locator('#toastUndo').tap(); await mp.wait_for_timeout(300)
        check(await num(mp, '#lcHidden') == 1, 'mobile: toast undo')
        await mp.locator('#fSize button[data-k="80"]').tap(); await mp.wait_for_timeout(400)
        mac = [float(t.replace(',', '').replace(' ac', '')) for t in await mp.locator('#plist .pi .acbig').all_inner_texts()]
        check(await mp.is_visible('#sizeBox') and mac and all(75 <= a <= 85 for a in mac), f'mobile: size chip ~80 visible and filters list ({len(mac)} rows)')
        await mp.locator('#fSize button[data-k="any"]').tap(); await mp.wait_for_timeout(300)
        mans = ['Yaggie MN', 'Wilkin 80s', 'Richland quarters', 'Big ground', 'E']
        mp.on('dialog', lambda d: asyncio.ensure_future(d.accept(mans.pop(0)) if (mans and d.type == 'prompt') else d.accept()))
        mh1 = await mp.evaluate('window.__land.hidden.toJSON()')
        await mp.locator('#sNew').tap(); await mp.wait_for_timeout(500)
        check(await num(mp, '#lcHidden') == 0, 'mobile: new tab has its own empty ruled-out list')
        await mp.locator('#lInView').uncheck(); await mp.locator('#fName').fill('yaggie'); await mp.wait_for_timeout(500)
        check(await num(mp, '#lcShown') == 259, 'mobile: name search Yaggie')
        await mp.locator('#plist .pi .main').first.tap(); await mp.wait_for_timeout(300)
        mh2 = await mp.evaluate('window.__land.hidden.toJSON()')
        await mp.locator('#stabList .stab').first.tap(); await mp.wait_for_timeout(500)
        check(await mp.evaluate('window.__land.hidden.toJSON()') == mh1 and await mp.input_value('#fName') == '', 'mobile: tab 1 list/filters untouched')
        await mp.reload(); await mp.wait_for_selector('body[data-land-ready="1"]', timeout=60000)
        await mp.locator('#stabList .stab').nth(1).tap(); await mp.wait_for_timeout(500)
        check(await mp.evaluate('window.__land.hidden.toJSON()') == mh2 and await mp.input_value('#fName') == 'yaggie', 'mobile: tab 2 persists across reload')
        await mp.locator('#fStates button[data-v="MN"]').tap(); await mp.wait_for_timeout(400)
        check(0 < await num(mp, '#lcShown') < 259, 'mobile: state chip MN narrows Yaggie')
        for _ in range(3): await mp.locator('#sNew').tap(); await mp.wait_for_timeout(300)
        sc = await mp.evaluate("(() => { const e = document.querySelector('#stabList'); return [e.scrollWidth, e.clientWidth]; })()")
        check(sc[0] > sc[1], f'mobile: tab strip scrolls sideways ({sc})')
        await mp.locator('#stabList .stab').nth(1).tap(); await mp.wait_for_timeout(500)
        await mp.evaluate("window.scrollTo(0,0); document.querySelector('#filtersBox').open = false; window.__land.map.setView([46.27, -96.62], 11.5); 0"); await mp.wait_for_timeout(2500)
        await mp.screenshot(path=f'{OUT}/land-tabs-mobile.png')
        await mp.screenshot(path=f'{OUT}/land-tabs-mobile-full.png', full_page=True)
        await mp.locator('#stabList .stab').first.tap(); await mp.wait_for_timeout(400)
        sw = await mp.evaluate('document.documentElement.scrollWidth'); check(sw <= 412, f'mobile no horizontal overflow ({sw})')
        await mp.evaluate('window.scrollTo(0,0)'); await mp.locator('#lbRestore').tap(); await mp.wait_for_timeout(300)
        await mp.evaluate("document.querySelector('#filtersBox').open = false; window.__land.map.setView([46.30, -96.66], 12); 0"); await mp.wait_for_timeout(2500)
        await mp.screenshot(path=f'{OUT}/land-mobile.png')
        await mp.screenshot(path=f'{OUT}/land-mobile-full.png', full_page=True)
        check(not errs, f'no JS errors {errs[:3]}')
        await b.close()
    print('FAILURES:', fails if fails else 'none')
    sys.exit(1 if fails else 0)
asyncio.run(main())
